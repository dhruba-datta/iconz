#!/usr/bin/env python3
"""Write the files launchers and the app read.

    python3 tool/build_icons.py                      # after any icon change
    python3 tool/build_icons.py --merge missing.txt  # add activities found on the phone

Inputs: icons/svg/*.svg (drawn by Iconz), the Arcticons import in icons/arcticons/
(tool/import_arcticons.py), and icons/icons.json (the Bangladesh list and its apps).

Writes app/src/main/res/drawable/<name>.xml for each Iconz SVG, res/xml/appfilter.xml and
assets/appfilter.xml (which app gets which icon; Iconz entries win over Arcticons'),
res/xml/drawable.xml (the icon picker list: Bangladesh, then everything) and
assets/icon_index.json (labels for the gallery).

missing.txt comes from tool/scan_phone.py. Each line is "<drawable or -> <package/activity>"
(anything after # is ignored); lines with a drawable are added to that icon's components.
Lines with "-" are apps with no icon yet; they are printed as a to-do.
"""
import json
import sys
from pathlib import Path
from xml.sax.saxutils import quoteattr

sys.path.insert(0, str(Path(__file__).resolve().parent))
import svg2vd  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ICONS = ROOT / "icons" / "icons.json"
OWN_SVG = ROOT / "icons" / "svg"
OWN_LIST = ROOT / "icons" / "own.txt"
ARC = ROOT / "icons" / "arcticons"
MAIN = ROOT / "app" / "src" / "main"
DRAWABLES = MAIN / "res" / "drawable"
HEADER = "<!-- Generated by tool/build_icons.py. Do not edit. -->"


def load():
    return json.loads(ICONS.read_text())


def save(data):
    lines = ["    " + json.dumps(i, ensure_ascii=False) for i in data["icons"]]
    head = json.dumps({k: v for k, v in data.items() if k != "icons"}, indent=2, ensure_ascii=False)[:-2]
    ICONS.write_text(head + ',\n  "icons": [\n' + ",\n".join(lines) + "\n  ]\n}\n")


def merge(data, path):
    by_name = {i["drawable"]: i for i in data["icons"]}
    added, todo = 0, []
    for raw in Path(path).read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        drawable, component = line.split()[:2]
        if drawable == "-":
            todo.append(component)
            continue
        icon = by_name.get(drawable)
        if icon is None:
            sys.exit(f"{path}: no icon named {drawable!r} in icons.json")
        if component not in icon["components"]:
            icon["components"].append(component)
            pkg = component.split("/")[0]
            if pkg not in icon["packages"]:
                icon["packages"].append(pkg)
            icon.pop("guess", None)
            added += 1
    save(data)
    print(f"added {added} components to icons.json")
    if todo:
        print(f"\n{len(todo)} apps have no icon yet:")
        print("\n".join("  " + t for t in todo))


def tsv(path):
    return [l.split("\t") for l in path.read_text().splitlines() if "\t" in l] if path.exists() else []


def build(data):
    # 1. Iconz's own drawings → VectorDrawables (replacing the previous run's).
    if OWN_LIST.exists():
        for name in OWN_LIST.read_text().split():
            (DRAWABLES / f"{name}.xml").unlink(missing_ok=True)
    own = sorted(p.stem for p in OWN_SVG.glob("*.svg"))
    for name in own:
        (DRAWABLES / f"{name}.xml").write_text(svg2vd.convert((OWN_SVG / f"{name}.svg").read_text()))
    OWN_LIST.write_text("\n".join(own) + "\n")

    arcticons = (ARC / "drawables.txt").read_text().split() if (ARC / "drawables.txt").exists() else []
    every = sorted(set(own) | set(arcticons))
    have = set(every)

    icons = data["icons"]
    names = [i["drawable"] for i in icons]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        sys.exit(f"duplicate drawables in icons.json: {sorted(dupes)}")
    missing = [n for n in names if n not in have]
    if missing:
        sys.exit(f"no icon file for: {missing} (draw icons/svg/<name>.svg or import Arcticons)")

    # 2. Which app gets which icon. Arcticons first, then Iconz's own entries on top.
    mapping = {comp: d for comp, d in tsv(ARC / "appfilter.tsv")}
    guesses = 0
    for i in icons:
        for comp in i["components"]:
            mapping[comp] = i["drawable"]
        if i.get("guess"):
            for pkg in i["packages"]:
                for act in ("MainActivity", "SplashActivity"):
                    comp = f"{pkg}/{pkg}.{act}"
                    if comp not in mapping:
                        mapping[comp] = i["drawable"]
                        guesses += 1
    items = [f"    <item component={quoteattr('ComponentInfo{' + c + '}')} drawable={quoteattr(d)} />"
             for c, d in sorted(mapping.items())]
    cals = [f"    <calendar component={quoteattr('ComponentInfo{' + c + '}')} prefix={quoteattr(p)} />"
            for c, p in tsv(ARC / "calendars.tsv")]
    appfilter = '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER + "\n<resources>\n" + "\n".join(items + cals) + "\n</resources>\n"
    for out in (MAIN / "res" / "xml" / "appfilter.xml", MAIN / "assets" / "appfilter.xml"):
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(appfilter)

    # 3. Icon picker list: Bangladesh first, then every icon.
    lines = ['<?xml version="1.0" encoding="utf-8"?>', HEADER, "<resources>", "    <version>1</version>",
             '    <category title="Bangladesh" />']
    lines += [f"    <item drawable={quoteattr(i['drawable'])} />" for i in sorted(icons, key=lambda i: i["label"].lower())]
    lines.append('    <category title="All icons" />')
    lines += [f"    <item drawable={quoteattr(d)} />" for d in every]
    lines.append("</resources>")
    (MAIN / "res" / "xml" / "drawable.xml").write_text("\n".join(lines) + "\n")

    index = {"apps": len(mapping),
             "icons": {i["drawable"]: {"label": i["label"], "packages": i["packages"]} for i in icons}}
    (MAIN / "assets" / "icon_index.json").write_text(json.dumps(index, indent=1, ensure_ascii=False) + "\n")

    print(f"{len(every)} icons ({len(own)} drawn by Iconz, {len(arcticons)} from Arcticons), "
          f"{len(mapping)} app entries ({guesses} guessed), {len(cals)} calendars")


if __name__ == "__main__":
    data = load()
    if len(sys.argv) == 3 and sys.argv[1] == "--merge":
        merge(data, sys.argv[2])
        data = load()
    elif len(sys.argv) != 1:
        sys.exit(__doc__)
    build(data)
