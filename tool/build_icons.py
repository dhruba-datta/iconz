#!/usr/bin/env python3
"""Write the files launchers and the app read, from icons/icons.json.

    python3 tool/build_icons.py                    # regenerate after editing icons.json
    python3 tool/build_icons.py --merge missing.txt  # add activities found on the phone

Writes app/src/main/res/xml/appfilter.xml (and the same file in assets/, where some
launchers look), res/xml/drawable.xml (the icon picker list) and assets/icon_index.json
(labels and packages, for the app's gallery).

missing.txt comes from tool/scan_phone.py. Each line is "<drawable or -> <package/activity>"
(anything after # is ignored); lines with a drawable are added to that icon's components.
Lines with "-" are apps with no icon yet; they are printed as a to-do.
"""
import json
import sys
from pathlib import Path
from xml.sax.saxutils import quoteattr

ROOT = Path(__file__).resolve().parent.parent
ICONS = ROOT / "icons" / "icons.json"
MAIN = ROOT / "app" / "src" / "main"
DRAWABLES = MAIN / "res" / "drawable"


def load():
    return json.loads(ICONS.read_text())


def merge(data, path):
    by_name = {i["drawable"]: i for i in data["icons"]}
    added, todo = 0, []
    for raw in Path(path).read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        drawable, component = line.split()[:2]
        if drawable == "-":
            todo.append(raw.strip())
            continue
        icon = by_name.get(drawable)
        if icon is None:
            sys.exit(f"{path}: no icon named {drawable!r}")
        if component not in icon["components"]:
            icon["components"].append(component)
            pkg = component.split("/")[0]
            if pkg not in icon["packages"]:
                icon["packages"].append(pkg)
            icon.pop("unverified", None)
            icon.pop("todo", None)
            added += 1
    lines = ["  " + json.dumps(i, ensure_ascii=False) for i in data["icons"]]
    body = {k: v for k, v in data.items() if k != "icons"}
    head = json.dumps(body, indent=2, ensure_ascii=False)[:-2]
    ICONS.write_text(head + ',\n  "icons": [\n' + ",\n".join("  " + l for l in lines) + "\n  ]\n}\n")
    print(f"added {added} components to icons.json")
    if todo:
        print(f"\n{len(todo)} apps still need an icon:")
        print("\n".join("  " + t for t in todo))


def build(data):
    icons = data["icons"]
    names = [i["drawable"] for i in icons]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        sys.exit(f"duplicate drawables: {sorted(dupes)}")
    missing = [n for n in names if not (DRAWABLES / f"{n}.xml").exists() and not (DRAWABLES / f"{n}.png").exists()]
    if missing:
        sys.exit(f"no drawable file for: {missing}")

    items = []
    for i in icons:
        for c in i["components"]:
            items.append(f'    <item component={quoteattr("ComponentInfo{" + c + "}")} drawable={quoteattr(i["drawable"])} />')
    appfilter = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/build_icons.py from icons/icons.json. -->\n<resources>\n' + "\n".join(items) + "\n</resources>\n"
    for out in (MAIN / "res" / "xml" / "appfilter.xml", MAIN / "assets" / "appfilter.xml"):
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(appfilter)

    groups = {}
    for i in icons:
        groups.setdefault(i["category"], []).append(i["drawable"])
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tool/build_icons.py from icons/icons.json. -->", '<resources>', '    <version>1</version>']
    for cat, ds in groups.items():
        lines.append(f"    <category title={quoteattr(cat)} />")
        lines += [f"    <item drawable={quoteattr(d)} />" for d in sorted(ds)]
    lines.append("</resources>")
    (MAIN / "res" / "xml" / "drawable.xml").write_text("\n".join(lines) + "\n")

    index = {i["drawable"]: {"label": i["label"], "packages": i["packages"]} for i in icons}
    (MAIN / "assets" / "icon_index.json").write_text(json.dumps(index, indent=1, ensure_ascii=False) + "\n")

    unmapped = [i["label"] for i in icons if not i["components"]]
    print(f"{len(icons)} icons, {len(items)} app entries; {len(unmapped)} icons not mapped to an app yet")


if __name__ == "__main__":
    data = load()
    if len(sys.argv) == 3 and sys.argv[1] == "--merge":
        merge(data, sys.argv[2])
        data = load()
    elif len(sys.argv) != 1:
        sys.exit(__doc__)
    build(data)
